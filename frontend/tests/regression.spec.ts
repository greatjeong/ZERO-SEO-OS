import { test, expect } from '@playwright/test'

test('site separation, queue, server snapshots and v1/v2 restore', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('사이트 이름').fill('테스트 사이트')
  await page.getByLabel('워드프레스 주소').fill('https://example.com')
  await page.getByRole('button', { name: '사이트 등록·저장' }).click()
  await page.getByPlaceholder('예: 워드프레스 SEO 최적화').fill('회귀 키워드')
  await page.getByRole('button', { name: '+ 등록', exact: true }).click()
  await page.getByRole('button', { name: '전체 선택', exact: true }).click()
  await page.getByRole('button', { name: /선택 키워드.*작업|작업.*추가/ }).click()
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await page.getByRole('button', { name: '다시 대기', exact: true }).click()
  await expect(page.getByRole('button', { name: '취소', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '현재 전체 데이터 서버 보관' }).click()
  await expect(page.getByText(/서버 저장 확인/)).toBeVisible()
  await page.getByRole('button', { name: 'A-2 사이트', exact: true }).click()
  await expect(page.getByText('회귀 키워드', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '서버 저장본 조회' }).click()
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: /저장본 #.*복원/ }).first().click()
  await expect(page.getByText(/복원 완료:/)).toBeVisible()
  await page.getByRole('button', { name: 'A-1 사이트', exact: true }).click()
  await expect(page.getByLabel('사이트 이름')).toHaveValue('테스트 사이트')
  await expect(page.getByRole('button', { name: '취소', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('사이트 이름')).toHaveValue('테스트 사이트')
  await expect(page.getByText('미검증', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '실제 연결 확인', exact: true }).click()
  await expect(page.getByText(/미연결 ·/)).toBeVisible()
  await expect(page.getByRole('button', { name: '테스트 초안 1개 저장' })).toBeDisabled()
  const v1 = { format: 'zero-seo-os-backup', version: 1, keywordsBySite: { 'A-1': ['v1 복원'], 'A-2': [] }, jobs: [] }
  await page.locator('input[type=file]').setInputFiles({ name: 'old.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(v1)) })
  await expect(page.getByText('v1 복원', { exact: true })).toBeVisible()
  await expect(page.getByLabel('사이트 이름')).toHaveValue('테스트 사이트')
})

test('connection success requires matching verified backend response', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('사이트 이름').fill('Mock')
  await page.getByLabel('워드프레스 주소').fill('https://example.com')
  await page.getByRole('button', { name: '사이트 등록·저장' }).click()
  await page.route('**/api/sites/verify', route => route.fulfill({ json: { verified: true, site: 'A-2', url: 'https://example.com', checkedAt: new Date().toISOString() } }))
  await page.getByRole('button', { name: '실제 연결 확인', exact: true }).click()
  await expect(page.getByText(/미연결 ·/)).toBeVisible()
  await page.route('**/api/sites/verify', route => route.fulfill({ json: { verified: true, site: 'A-1', url: 'https://example.com', checkedAt: new Date().toISOString() } }))
  await page.getByRole('button', { name: '실제 연결 확인', exact: true }).click()
  await expect(page.getByText(/인증 연결 검증 성공/)).toBeVisible()
  await page.reload()
  await expect(page.getByText('미검증', { exact: true })).toBeVisible()
})
